// Main Helper function to translate item name
export function translateRecordedItem(name: string, lang: LanguageCode | string = 'en'): string {
  if (lang === 'en' || !name) return name;

  const lower = name.toLowerCase().trim();

  // 1. Direct match on recorded items dictionary
  const exact = RECORDED_ITEMS_TRANSLATIONS[lower];
  if (exact) {
    return exact[lang] || exact['hi'] || name;
  }

  // 2. Multi-word vocabulary replacement
  let translated = name;
  let hasReplaced = false;

  for (const [key, valObj] of Object.entries(RECORDED_ITEMS_TRANSLATIONS)) {
    if (lower.includes(key)) {
      const replacement = valObj[lang] || valObj['hi'];
      if (replacement) {
        const regex = new RegExp(key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
        translated = translated.replace(regex, replacement);
        hasReplaced = true;
        break;
      }
    }
  }

  if (hasReplaced) return translated;

  // 3. Check culinary vocabulary
  for (const [key, valObj] of Object.entries(CULINARY_VOCABULARY)) {
    if (lower.includes(key)) {
      const replacement = valObj[lang] || valObj['hi'];
      if (replacement) {
        const regex = new RegExp(`\\b${key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi');
        if (regex.test(translated)) {
          translated = translated.replace(regex, replacement);
          hasReplaced = true;
        }
      }
    }
  }

  return translated;
}

// Helper to format units
export function translateRecordedUnit(unit: string, lang: LanguageCode | string = 'en'): string {
  if (lang === 'en' || !unit) return unit;
  const lower = unit.toLowerCase().trim();

  // Check direct unit translations
  for (const [uKey, uDict] of Object.entries(UNIT_TRANSLATIONS)) {
    if (lower.startsWith(uKey) || lower.includes(uKey)) {
      const trans = uDict[lang] || uDict['hi'];
      if (trans) {
        return unit.replace(new RegExp(`\\b${uKey}\\b`, 'gi'), trans);
      }
    }
  }
  return unit;
}

// Helper to format locations
export function translateRecordedLocation(loc: string, lang: LanguageCode | string = 'en'): string {
  if (lang === 'en' || !loc) return loc;
  const lower = loc.toLowerCase().trim();

  const exact = ZONE_TRANSLATIONS[lower];
  if (exact) {
    return exact[lang] || exact['hi'] || loc;
  }

  if (lower.startsWith('cold storage')) {
    const num = loc.match(/#\d+/);
    const hiPrefix = lang === 'hi' ? 'शीत भंडारण' : (ZONE_TRANSLATIONS['cold storage'][lang] || 'कोल्ड स्टोरेज');
    return `${hiPrefix} ${num ? num[0] : ''}`.trim();
  }

  if (lower.startsWith('zone')) {
    const code = loc.replace(/zone/i, '').trim();
    const hiPrefix = lang === 'hi' ? 'ज़ोन' : 'জোন';
    return `${hiPrefix} ${code}`.trim();
  }

  return loc;
}

